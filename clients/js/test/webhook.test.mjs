import test from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { createRequire } from "node:module";
import { verifyWebhook, signWebhook, WebhookVerificationError } from "../dist/esm/index.js";

const vectors = JSON.parse(readFileSync(new URL("../../test-vectors/webhook.json", import.meta.url), "utf8"));

test("signatures match vectors generated by the server", () => {
  for (const v of vectors.vectors) {
    assert.equal(signWebhook(v.body, v.secret, v.timestamp), v.signature);
  }
});

test("verifies server vectors", () => {
  for (const v of vectors.vectors.filter((v) => v.body)) {
    const event = verifyWebhook(v.body, { "X-Gateway-Signature": v.header }, v.secret, 300, v.timestamp + 10);
    assert.equal(typeof event, "object");
  }
});

test("accepts bytes and Headers", () => {
  const v = vectors.vectors[0];
  const headers = new Headers({ [vectors.header]: v.header });
  verifyWebhook(Buffer.from(v.body), headers, v.secret, 300, v.timestamp);
});

test("rejects tampered body, wrong secret, and tampered signature", () => {
  const v = vectors.vectors[0];
  const headers = { [vectors.header]: v.header };
  assert.throws(() => verifyWebhook(v.body + " ", headers, v.secret, 300, v.timestamp), WebhookVerificationError);
  assert.throws(() => verifyWebhook(v.body, headers, "wrong", 300, v.timestamp), WebhookVerificationError);
  const flipped = v.header.replace(/.$/, (c) => (c === "0" ? "1" : "0"));
  assert.throws(() => verifyWebhook(v.body, { [vectors.header]: flipped }, v.secret, 300, v.timestamp), /does not match/);
});

test("rejects a replayed signature with a changed timestamp", () => {
  const v = vectors.vectors[0];
  const header = v.header.replace(`t=${v.timestamp}`, `t=${v.timestamp + 1}`);
  assert.throws(() => verifyWebhook(v.body, { [vectors.header]: header }, v.secret, 300, v.timestamp), WebhookVerificationError);
});

test("rejects stale and future timestamps, tolerance 0 disables the check", () => {
  const v = vectors.vectors[0];
  const headers = { [vectors.header]: v.header };
  assert.throws(() => verifyWebhook(v.body, headers, v.secret, 300, v.timestamp + 301), /tolerance/);
  assert.throws(() => verifyWebhook(v.body, headers, v.secret, 300, v.timestamp - 301), /tolerance/);
  verifyWebhook(v.body, headers, v.secret, 300, v.timestamp + 300);
  verifyWebhook(v.body, headers, v.secret, 0, v.timestamp + 999999);
});

test("rejects missing and malformed headers", () => {
  const v = vectors.vectors[0];
  assert.throws(() => verifyWebhook(v.body, {}, v.secret), { reason: "missing_header" });
  assert.throws(() => verifyWebhook(v.body, { [vectors.header]: "garbage" }, v.secret), { reason: "malformed_header" });
  assert.throws(() => verifyWebhook(v.body, { [vectors.header]: "t=abc,v1=00" }, v.secret), { reason: "malformed_header" });
});

test("commonjs build exposes the same api", () => {
  const cjs = createRequire(import.meta.url)("../dist/cjs/index.js");
  assert.equal(typeof cjs.verifyWebhook, "function");
  assert.equal(typeof cjs.Gateway, "function");
});
